#!/usr/bin/env node
/**
 * Inlines the whole site into single self-contained HTML files.
 *
 *   dist/drawing-atlas.html  full standalone page — email it, keep it offline,
 *                            open it with no server and no network
 *   dist/artifact.html       same page without the doctype/html/head/body
 *                            wrapper, for hosts that supply their own skeleton
 *
 * Reads index.html and follows its own <link>/<script> tags, so the bundle can
 * never drift from what the site actually loads.
 *
 * Run: node scripts/bundle.mjs
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dist = path.join(root, "dist");

const html = await readFile(path.join(root, "index.html"), "utf8");

/* Nothing in this project uses </script> or </style> inside its own source, but
   a future data entry easily could, and it would silently truncate the bundle. */
function guard(text, tag, file) {
  const needle = "</" + tag;
  if (text.toLowerCase().includes(needle)) {
    throw new Error(`${file} contains "${needle}" which would break the inlined <${tag}> block`);
  }
  return text;
}

/* ---- collect the assets index.html actually references ---------------- */

const cssHrefs = [...html.matchAll(/<link[^>]+rel="stylesheet"[^>]+href="([^"]+)"/g)].map((m) => m[1]);
const scriptSrcs = [...html.matchAll(/<script[^>]+src="([^"]+)"/g)].map((m) => m[1]);

if (!cssHrefs.length) throw new Error("index.html references no stylesheet");
if (!scriptSrcs.length) throw new Error("index.html references no scripts");

const styles = [];
for (const href of cssHrefs) {
  styles.push(guard(await readFile(path.join(root, href), "utf8"), "style", href));
}

const scripts = [];
for (const src of scriptSrcs) {
  scripts.push({ src, code: guard(await readFile(path.join(root, src), "utf8"), "script", src) });
}

/* ---- rebuild the document -------------------------------------------- */

const title = (html.match(/<title>([^<]*)<\/title>/) || [, "Drawing Atlas"])[1];
const description = (html.match(/<meta name="description" content="([^"]*)"/) || [, ""])[1];

// Body markup, minus the tags we are replacing with inlined equivalents.
const body = html
  .replace(/^[\s\S]*?<body[^>]*>/i, "")
  .replace(/<\/body>[\s\S]*$/i, "")
  .replace(/^\s*<script[^>]+src="[^"]+"><\/script>\s*$/gm, "")
  .trim();

const inlineStyle = `<style>\n${styles.join("\n")}\n</style>`;
const inlineScripts = scripts
  .map((s) => `<script>\n/* ${s.src} */\n${s.code}\n</script>`)
  .join("\n");

const banner = `<!-- Drawing Atlas — single-file build, generated by scripts/bundle.mjs.
     Do not edit: change the source files and re-run the bundler.
     Source: https://github.com/SirawatSp/drawing-atlas -->`;

const standalone = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<meta name="description" content="${description}">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'%3E%3Ctext y='.9em' font-size='90'%3E%E2%9D%80%3C/text%3E%3C/svg%3E">
${banner}
${inlineStyle}
</head>
<body>
${body}
${inlineScripts}
</body>
</html>
`;

// Host-wrapped variant: no doctype/html/head/body of our own.
const embedded = `<title>${title}</title>
${banner}
${inlineStyle}
${body}
${inlineScripts}
`;

await mkdir(dist, { recursive: true });
await writeFile(path.join(dist, "drawing-atlas.html"), standalone);
await writeFile(path.join(dist, "artifact.html"), embedded);

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + " KB";
console.log(`Inlined ${styles.length} stylesheet(s) and ${scripts.length} script(s).`);
console.log(`  dist/drawing-atlas.html  ${kb(standalone)}`);
console.log(`  dist/artifact.html       ${kb(embedded)}`);

for (const [name, out] of [["standalone", standalone], ["embedded", embedded]]) {
  if (/<(link|script)[^>]+(href|src)="(?!data:)/.test(out)) {
    throw new Error(`${name} build still references an external asset`);
  }
}
console.log("No external references — both builds are self-contained.");
